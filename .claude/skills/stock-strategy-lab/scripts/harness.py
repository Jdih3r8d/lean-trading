import pandas as pd

LAB = os.path.dirname(os.path.abspath(__file__))
COST_BASE = 0.0005
COST_STRESS = 0.0015
FIN_RATE = 0.06      # annual financing on leverage above 1x
BORROW_RATE = 0.005  # annual borrow fee on shorts


