"""Shared, audited evaluation harness for a single-stock strategy lab (generic version).

EVERY research agent must evaluate strategies with these functions so results are comparable.
Do NOT edit this file inside a lab; copy helpers into your own module if you need variants.

Lab layout (created by scripts/new_lab.sh):
  <lab>/harness.py, <lab>/engine.py, <lab>/PROTOCOL.md, <lab>/config.json
  <lab>/data/main.csv   daily OHLCV of the stock under study (split-adjusted), columns date,open,high,low,close,volume
  <lab>/data/baseline_weights.csv  (optional) target weights of the current reference strategy, columns date,weight

Conventions
-----------
* A signal / target weight decided with information up to the CLOSE of day t is executed at the OPEN of day t+1
  (default, exec='open'). exec='close' (market-on-close at day t) is a robustness variant only and must never be the
  headline result (the same close is both signal and fill).
* Costs are per side, as a fraction of traded notional: COST_BASE = 5 bp, COST_STRESS = 15 bp. Fractional / leveraged /
  short weights are modelled as a position REBALANCED to the target every session and the rebalancing turnover IS
  charged. Leverage above 1 pays FIN_RATE per year on the borrowed part, shorts pay BORROW_RATE per year. Idle cash
  earns nothing (conservative for low-exposure strategies).
* Periods come from config.json (keys is_start, is_end, oos_start, rec_start, ytd_year): IS is the only period where
  parameters may be chosen; OOS is everything after it; REC the last ~3 years; Y_YTD the current year.
  Trades are assigned to a period by ENTRY date.
* walk_forward_weights() re-selects the best candidate every January using only past data and stitches WEIGHTS
  (switching costs and timing exact).

History: this harness was audited by an independent agent during the TSLA study (2026-11). Bugs fixed then: long<->short
flip days double-counted in the trade ledger; rebalancing turnover, leverage financing and short borrow not charged;
MDD ignoring a first-day loss; permutation tests counting NaN sims as losses and lacking the (1+k)/(1+n) correction;
trades filtered by signal date; return-stitching walk-forward with a one-gap-per-year look-ahead.
"""
import json
