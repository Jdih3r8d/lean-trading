# ---------------------------------------------------------------- weights engine
def _legs(df, w, exec):
    """Per-day return legs used by run_weights and trades_from_weights."""
    w = pd.Series(w, index=df.index).astype(float).fillna(0.0)
    O, C = df['open'], df['close']
    if exec == 'open':
        gap = (O / C.shift(1) - 1).fillna(0.0)
        intra = C / O - 1
        w_prev = w.shift(2).fillna(0.0)   # held through the overnight gap into day t
        w_new = w.shift(1).fillna(0.0)    # set at today's open
        # the previous target drifts over the last open->open interval, then is rebalanced to w_new
        oo = (O / O.shift(1) - 1).fillna(0.0)
        w_drift = (w_prev * (1 + oo) / (1 + w_prev * oo)).where(w_prev != 0, 0.0)
        turn = (w_new - w_drift).abs()
        fin = (w_new.abs() - 1).clip(lower=0) * FIN_RATE / 252 + (-w_new).clip(lower=0) * BORROW_RATE / 252
        return dict(w=w, w_prev=w_prev, w_new=w_new, gap=gap, intra=intra, turn=turn, fin=fin)
    if exec == 'close':
        ret = C.pct_change().fillna(0.0)
        w_prev = w.shift(1).fillna(0.0)
        w_drift = (w_prev * (1 + ret) / (1 + w_prev * ret)).where(w_prev != 0, 0.0)
        turn = (w - w_drift).abs()
        fin = (w_prev.abs() - 1).clip(lower=0) * FIN_RATE / 252 + (-w_prev).clip(lower=0) * BORROW_RATE / 252
        return dict(w=w, w_prev=w_prev, ret=ret, turn=turn, fin=fin)
    raise ValueError(exec)


def run_weights(df, w, cost=COST_BASE, exec='open'):
    """Daily strategy returns (net of costs) for a target-weight series.

    w : target weight decided at the close of each day (0 flat, 1 long, 0.5 half, -1 short, 1.5 leveraged).
    exec='open' : w[t] is traded at open[t+1]; overnight gap close[t]->open[t+1] earns w[t-1],
                  the intraday leg open[t+1]->close[t+1] earns w[t].
    exec='close': w[t] is traded at close[t]; day t+1 earns w[t]*(close[t+1]/close[t]-1).
    """
    L = _legs(df, w, exec)
    if exec == 'open':
        r = (1 + L['w_prev'] * L['gap']) * (1 + L['w_new'] * L['intra']) - 1 - cost * L['turn'] - L['fin']
    else:
        r = L['w_prev'] * L['ret'] - cost * L['turn'] - L['fin']
    return r.fillna(0.0)


def trades_from_weights(df, w, cost=COST_BASE, exec='open'):
    """Split a weight series into trades = maximal runs of the same non-zero sign.
    Each trade owns its entry leg (intraday of the entry day + entry cost), all full days in between, and its
    exit leg (overnight gap into the exit open + exit cost). Flip days are split between the two trades, so
    the ledger reconciles with the daily equity. Trade return is per unit of the run's mean |weight|.
    Returns DataFrame[signal_date, entry, exit, days, ret, side]."""
    L = _legs(df, w, exec)
    wv = L['w'].values
    s = np.sign(wv)
    n = len(s)
    r_full = run_weights(df, L['w'], cost, exec).values
    out = []
    i = 0
    while i < n:
        if s[i] == 0:
            i += 1
            continue
        j = i
        while j + 1 < n and s[j + 1] == s[i]:
            j += 1
        if exec == 'open':
            a, b = i + 1, j + 2                    # entry day (open fill) and exit day (open fill)
            if a >= n:                             # signal on the last bar: not executed yet
                break
            legs = [wv[i] * L['intra'].iloc[a] - cost * abs(wv[i]) - L['fin'].iloc[a]]
            legs += list(r_full[a + 1:min(b, n)])
            if b < n:
                legs.append(wv[j] * L['gap'].iloc[b] - cost * abs(wv[j]))
        else:
            a, b = i, j + 1                        # entry at close i, exit at close j+1
            legs = [-cost * abs(wv[i])]
            legs += list(r_full[a + 1:min(b, n)])
            if b < n:
                legs.append(wv[j] * L['ret'].iloc[b] - cost * abs(wv[j]) - L['fin'].iloc[b])
        scale = np.abs(wv[i:j + 1]).mean()
        tr = (np.prod(1 + np.array(legs)) - 1) / scale if scale > 0 else 0.0
        out.append((df.index[i], df.index[a], df.index[min(b, n - 1)], j - i + 1, tr, int(s[i])))
        i = j + 1
    return pd.DataFrame(out, columns=['signal_date', 'entry', 'exit', 'days', 'ret', 'side'])


# ---------------------------------------------------------------- statistics
def perf(r, lo=None, hi=None):
    r = r.loc[lo:hi] if (lo or hi) else r
    if len(r) < 2 or r.std() == 0:
        return dict(cagr=np.nan, vol=np.nan, sharpe=np.nan, mdd=np.nan, total=np.nan)
    eq = np.r_[1.0, (1 + r.values).cumprod()]
    yrs = len(r) / 252
    return dict(cagr=eq[-1] ** (1 / yrs) - 1, vol=r.std() * np.sqrt(252),
                sharpe=r.mean() / r.std() * np.sqrt(252), mdd=(eq / np.maximum.accumulate(eq) - 1).min(),
                total=eq[-1] - 1)


def exposure(w, lo=None, hi=None):
    """(fraction of sessions with a position, mean |weight|)."""
    w = pd.Series(w).fillna(0.0)
    w = w.loc[lo:hi] if (lo or hi) else w
    return float((w != 0).mean()), float(w.abs().mean())


def trade_stats(t, lo=None, hi=None):
    if lo or hi:
        m = pd.Series(True, index=t.index)
        if lo: m &= t.entry >= pd.Timestamp(lo)
        if hi: m &= t.entry <= pd.Timestamp(hi)
        t = t[m]
    x = t.ret.values
    n = len(x)
    if n == 0:
        return dict(n=0, avg=np.nan, med=np.nan, win=np.nan, avg_win=np.nan, avg_loss=np.nan, pf=np.nan, t=np.nan, days=np.nan)
    sd = x.std(ddof=1) if n > 1 else np.nan
    return dict(n=n, avg=x.mean(), med=np.median(x), win=(x > 0).mean(),
                avg_win=x[x > 0].mean() if (x > 0).any() else 0.0,
                avg_loss=x[x < 0].mean() if (x < 0).any() else 0.0,
                pf=x[x > 0].sum() / -x[x < 0].sum() if (x < 0).any() else np.inf,
                t=x.mean() / sd * np.sqrt(n) if n > 1 and sd > 0 else np.nan, days=t.days.mean())


def report(df, w, name='', exec='open'):
    """Standard report: perf + exposure + trade stats per period at base cost, plus OOS/ALL at stress cost."""
    rows = {}
    for cost_name, cost in (('base', COST_BASE), ('stress', COST_STRESS)):
        r = run_weights(df, w, cost, exec)
        t = trades_from_weights(df, w, cost, exec)
        for p, (lo, hi) in PERIODS.items():
            if cost_name == 'stress' and p not in ('OOS', 'ALL'):
                continue
            ex, gross = exposure(pd.Series(w, index=df.index), lo, hi)
            d = {**{'p_' + k: v for k, v in perf(r, lo, hi).items()}, 'p_expo': ex, 'p_avgw': gross,
                 **{'t_' + k: v for k, v in trade_stats(t, lo, hi).items()}}
            rows[f'{p}|{cost_name}'] = d
    out = pd.DataFrame(rows).T
    out.index.name = name
    return out


