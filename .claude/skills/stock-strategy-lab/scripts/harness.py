# ---------------------------------------------------------------- walk-forward
def _score(tr, score):
    if score == 'sharpe':
        return tr.mean() / tr.std().replace(0, np.nan) * np.sqrt(252)
    if score == 'cagr':
        return (1 + tr).prod() ** (252 / len(tr)) - 1
    if score == 'calmar':
        eq = (1 + tr).cumprod()
        return ((eq.iloc[-1]) ** (252 / len(tr)) - 1) / (-(eq / eq.cummax() - 1).min()).replace(0, np.nan)
    return score(tr)


def walk_forward_weights(df, cand_weights, train_years=3, start_year=None, end_year=None, score='sharpe',
                         expanding=False, top_k=1, cost=COST_BASE, exec='open'):
    """cand_weights: dict name -> causal weight Series. Every January of year Y, score each candidate's daily
    returns on [Y-train_years, Y-1] (or from the start if expanding) and hold the top_k (equal weight) during
    Y. Weights are stitched: the target decided at the last close of Y-1 (when the pick is known) already
    follows Y's pick; switching costs are included. Returns (daily returns from start_year, weights, picks)."""
    first = df.index[0]
    if start_year is None:   # first year whose whole training window lies inside the data
        start_year = first.year + train_years + (0 if (first.month, first.day) <= (1, 7) else 1)
    if end_year is None:
        end_year = df.index[-1].year
    R = pd.DataFrame({k: run_weights(df, v, cost, exec) for k, v in cand_weights.items()})
    Wd = pd.DataFrame({k: pd.Series(v, index=df.index).astype(float).fillna(0.0) for k, v in cand_weights.items()})
    W = pd.Series(0.0, index=df.index)
    picks = []
    for y in range(start_year, end_year + 1):
        lo = R.index[0] if expanding else pd.Timestamp(f'{y - train_years}-01-01')
        tr = R.loc[lo:pd.Timestamp(f'{y - 1}-12-31')]
        best = list(_score(tr, score).fillna(-np.inf).nlargest(top_k).index)
        picks.append((y, best))
        yr_idx = df.index[df.index.year == y]
        if len(yr_idx) == 0:
            continue
        span = df.index[df.index < yr_idx[0]][-1:].append(yr_idx[:-1])
        W.loc[span] = Wd.loc[span, best].mean(axis=1)
    r = run_weights(df, W, cost, exec)
    return r.loc[pd.Timestamp(f'{start_year}-01-01'):], W, picks


def walk_forward(cands, train_years=3, start_year=None, end_year=None, score='sharpe', expanding=False, top_k=1):
    """Legacy return-stitching walk-forward (no switching cost; one overnight gap per year of timing slack).
    Prefer walk_forward_weights(). cands: dict name -> daily return Series."""
    R = pd.DataFrame(cands).fillna(0)
    if start_year is None:
        start_year = R.index[0].year + train_years + (0 if (R.index[0].month, R.index[0].day) <= (1, 7) else 1)
    if end_year is None:
        end_year = R.index[-1].year
    out, picks = [], []
    for y in range(start_year, end_year + 1):
        lo = R.index[0] if expanding else pd.Timestamp(f'{y - train_years}-01-01')
        tr = R.loc[lo:pd.Timestamp(f'{y - 1}-12-31')]
        best = list(_score(tr, score).fillna(-np.inf).nlargest(top_k).index)
        picks.append((y, best))
        out.append(R.loc[str(y), best].mean(axis=1))
    return pd.concat(out), picks


# ---------------------------------------------------------------- significance
def shift_permutation_test(df, w, n_perm=2000, min_shift=63, cost=COST_BASE, exec='open', lo=None, hi=None, seed=0):
    """Circularly shift the weight series by a random offset (>= min_shift days) and recompute Sharpe on
    [lo, hi]. Preserves exposure and signal autocorrelation, destroys timing.
    Returns (actual_sharpe, p_value, n_valid) with p = (1 + #{sim >= actual}) / (1 + n_valid); shifted
    series with no activity in the window (NaN Sharpe) are dropped."""
    rng = np.random.default_rng(seed)
    lo = PERIODS['ALL'][0] if lo is None else lo
    w = pd.Series(w, index=df.index).fillna(0.0)
    base = perf(run_weights(df, w, cost, exec), lo, hi)['sharpe']
    if np.isnan(base):
        return base, np.nan, 0
    n = len(w)
    sims = []
    for _ in range(n_perm):
        k = int(rng.integers(min_shift, n - min_shift))
        ws = pd.Series(np.roll(w.values, k), index=w.index)
        sims.append(perf(run_weights(df, ws, cost, exec), lo, hi)['sharpe'])
    sims = np.array(sims)
    sims = sims[~np.isnan(sims)]
    return base, float((1 + np.sum(sims >= base)) / (1 + len(sims))), len(sims)


def random_entry_test(df, trades, n_perm=5000, lo=None, hi=None, seed=0, cost=COST_BASE):
    """LONG, exec='open', fixed-holding event trades only: compare the mean trade return with random entries
    in the same period with the same holding lengths (entry at open, exit at the open `days` sessions later).
    `cost` must equal the cost used to build `trades`. Returns (mean_actual, mean_random, p) with p=(1+k)/(1+n)."""
    if 'side' in trades and (trades.side < 0).any():
        raise ValueError('random_entry_test supports long-only trades')
    rng = np.random.default_rng(seed)
    t = trades
    if lo: t = t[t.entry >= pd.Timestamp(lo)]
    if hi: t = t[t.entry <= pd.Timestamp(hi)]
    if len(t) == 0:
        return np.nan, np.nan, np.nan
    O = df['open'].values
    idx = df.index
    lo_i = idx.searchsorted(pd.Timestamp(lo)) if lo else 0
    hi_i = idx.searchsorted(pd.Timestamp(hi)) if hi else len(idx) - 1
    hold = t.days.values.astype(int)
    actual = t.ret.mean()
    sims = np.empty(n_perm)
    for k in range(n_perm):
        s = rng.integers(lo_i, max(lo_i + 1, hi_i - hold.max() - 2), size=len(hold))
        e = np.minimum(s + 1 + hold, len(O) - 1)
        sims[k] = np.mean(O[e] / O[s + 1] - 1 - 2 * cost)
    return actual, sims.mean(), float((1 + np.sum(sims >= actual)) / (1 + n_perm))


def bootstrap_ci(x, n=10000, q=(5, 95), seed=0):
    """Percentile bootstrap of the mean. Default q=(5,95) is a 90% interval."""
    rng = np.random.default_rng(seed)
    x = np.asarray(x)
    if len(x) < 3:
        return (np.nan, np.nan)
    m = np.array([rng.choice(x, len(x)).mean() for _ in range(n)])
    return tuple(np.percentile(m, q))


def deflated_sharpe(r, n_trials, sr_trials_std=None):
    """Bailey & Lopez de Prado (2014) deflated Sharpe ratio: probability that the true SR > 0 after selecting
    the best of n_trials. r: daily returns of the chosen strategy. sr_trials_std: std of the DAILY
    (non-annualised) Sharpe ratios across the trials you ran -- pass the real value; if None a conservative
    0.5/sqrt(252) is assumed."""
    from scipy.stats import norm, skew, kurtosis
    r = np.asarray(r)
    r = r[~np.isnan(r)]
    T = len(r)
    sr = r.mean() / r.std()
    g3, g4 = skew(r), kurtosis(r, fisher=False)
    v = sr_trials_std if sr_trials_std is not None else 0.5 / np.sqrt(252)
    emc = 0.5772156649
    sr0 = v * ((1 - emc) * norm.ppf(1 - 1 / n_trials) + emc * norm.ppf(1 - 1 / (n_trials * np.e))) if n_trials > 1 else 0.0
    z = (sr - sr0) * np.sqrt(T - 1) / np.sqrt(1 - g3 * sr + (g4 - 1) / 4 * sr ** 2)
    return float(norm.cdf(z))


# ---------------------------------------------------------------- reusable building blocks
def fixed_hold(signal, hold, index):
    """Weight 1 on the closes t..t+hold-1 after each signal close t (buy open t+1, sell open t+1+hold).
    Signals while holding and on the exit-decision close are ignored (next check at t+hold+1)."""
    s = np.asarray(signal, bool)
    w = np.zeros(len(s))
    i = 0
    while i < len(s):
        if s[i]:
            w[i:i + hold] = 1.0
            i += hold + 1
        else:
            i += 1
    return pd.Series(w, index=index)


def trend_capitulation_weights(df, fast=10, slow=30, drop=0.12, lookback=5, hold=3):
    """The two-module system that worked as a first reference for TSLA (2010-2026): 50% 'trend' (SMA fast > SMA slow)
    + 50% 'capitulation' (close <= (1-drop) * close `lookback` sessions earlier, hold `hold` sessions).
    Re-tune fast/slow/drop on the IS period of the new stock before using it as a baseline."""
    c = df['close']
    a = (c.rolling(fast).mean() > c.rolling(slow).mean()).astype(float)
    b = fixed_hold((c / c.shift(lookback) - 1 <= -drop).fillna(False).values, hold, df.index)
    return {'trend': a, 'capitulation': b, 'mix_50_50': 0.5 * a + 0.5 * b}
